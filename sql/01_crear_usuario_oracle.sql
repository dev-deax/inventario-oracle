-- Ejecutar como SYS o SYSTEM conectado a XEPDB1, no a CDB$ROOT.
-- SQL*Plus y SQLcl solicitan la contraseña sin guardarla en este archivo.
WHENEVER SQLERROR EXIT SQL.SQLCODE
ACCEPT clave CHAR PROMPT 'Contraseña para INVENTARIO_APP: ' HIDE
CREATE USER INVENTARIO_APP IDENTIFIED BY "&clave";
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO INVENTARIO_APP;
ALTER USER INVENTARIO_APP QUOTA 50M ON USERS;
UNDEFINE clave
