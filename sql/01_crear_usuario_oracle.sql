-- Ejecutar como SYS o SYSTEM conectado a XEPDB1, no a CDB$ROOT.
-- SQL*Plus y SQLcl solicitan la contraseña sin guardarla en este archivo.
WHENEVER SQLERROR EXIT SQL.SQLCODE
ACCEPT clave CHAR PROMPT 'Contraseña para INVENTARIO_CURSO: ' HIDE
CREATE USER INVENTARIO_CURSO IDENTIFIED BY "&clave" DEFAULT TABLESPACE USERS;
GRANT CREATE SESSION, CREATE TABLE, CREATE SEQUENCE TO INVENTARIO_CURSO;
ALTER USER INVENTARIO_CURSO QUOTA 50M ON USERS;
UNDEFINE clave
