WHENEVER SQLERROR EXIT SQL.SQLCODE
CREATE SEQUENCE proveedores_seq START WITH 1 INCREMENT BY 1;
CREATE TABLE proveedores (
    id NUMBER PRIMARY KEY,
    nombre VARCHAR2(120) NOT NULL,
    empresa VARCHAR2(150) NOT NULL,
    nit VARCHAR2(30) NOT NULL,
    telefono VARCHAR2(30),
    email VARCHAR2(150),
    creado_en TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT uq_proveedores_nit UNIQUE (nit)
);
